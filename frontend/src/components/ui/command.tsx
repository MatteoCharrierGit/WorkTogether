import { Search } from 'lucide-react'
import { cn } from '@/lib/utils'
import { Dialog, DialogContent, DialogTitle } from '@/components/ui/dialog'

const Command = React.forwardRef<
  React.ElementRef<typeof CommandPrimitive>,
  React.ComponentPropsWithoutRef<typeof CommandPrimitive>
>(({ className, ...props }, ref) => (
  <CommandPrimitive
    ref={ref}
    className={cn('flex h-full w-full flex-col overflow-hidden rounded-[inherit] bg-popover text-popover-foreground', className)}
    {...props}
  />
))
Command.displayName = CommandPrimitive.displayName

/** Palette comandi in un dialog (⌘K). */
function CommandDialog({
  children,
  title = 'Cerca',
  commandProps,
  ...props
}: React.ComponentProps<typeof Dialog> & {
  title?: string
  commandProps?: React.ComponentPropsWithoutRef<typeof CommandPrimitive>
  children?: React.ReactNode
}) {
  return (
    <Dialog {...props}>
      <DialogContent hideClose className="top-[15%] max-w-xl translate-y-0 gap-0 overflow-hidden p-0 data-[state=open]:slide-in-from-top-2" aria-describedby={undefined}>
        <DialogTitle className="sr-only">{title}</DialogTitle>
        <Command
          className="[&_[cmdk-group-heading]]:px-2 [&_[cmdk-group-heading]]:py-1.5 [&_[cmdk-group-heading]]:text-xs [&_[cmdk-group-heading]]:font-medium [&_[cmdk-group-heading]]:text-muted-foreground"
          {...commandProps}
        >
          {children}
        </Command>
      </DialogContent>
    </Dialog>
  )
}

